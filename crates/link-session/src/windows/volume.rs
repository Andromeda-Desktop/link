//! The default output device's volume and mute through `IAudioEndpointVolume`, watched with its change callback and
//! the device enumerator's default-device callback. COM is set up for the thread by `win::run`.

#![allow(unsafe_code, reason = "FFI: COM calls on interfaces this struct owns")]
#![allow(
    clippy::unused_async,
    clippy::unused_async_trait_impl,
    reason = "the Linux backend's interface, whose calls wait"
)]

use tokio::sync::mpsc;
use windows::Win32::Media::Audio::Endpoints::{IAudioEndpointVolume, IAudioEndpointVolumeCallback};
use windows::Win32::Media::Audio::{IMMDeviceEnumerator, IMMNotificationClient, MMDeviceEnumerator, eConsole, eRender};
use windows::Win32::System::Com::{CLSCTX_ALL, CoCreateInstance};

use watch::{DeviceWatch, LevelWatch};

enum Change {
    Level,
    DefaultDevice,
}

pub struct Volume {
    enumerator: IMMDeviceEnumerator,
    /// The default output's control, which `level_watch` is registered on.
    endpoint: IAudioEndpointVolume,
    level_watch: IAudioEndpointVolumeCallback,
    device_watch: IMMNotificationClient,
    changes: mpsc::UnboundedReceiver<Change>,
}

impl Volume {
    /// None without a default output device.
    pub async fn connect() -> anyhow::Result<Option<Self>> {
        // SAFETY: COM is initialized on this thread (win::run).
        let enumerator: IMMDeviceEnumerator = unsafe { CoCreateInstance(&MMDeviceEnumerator, None, CLSCTX_ALL)? };
        let Ok(endpoint) = open(&enumerator) else { return Ok(None) };
        let (sender, changes) = mpsc::unbounded_channel();
        let level_watch: IAudioEndpointVolumeCallback = LevelWatch(sender.clone()).into();
        let device_watch: IMMNotificationClient = DeviceWatch(sender).into();
        // SAFETY: both callbacks stay registered until `Drop` removes them.
        unsafe {
            endpoint.RegisterControlChangeNotify(&level_watch)?;
            enumerator.RegisterEndpointNotificationCallback(&device_watch)?;
        }
        Ok(Some(Self { enumerator, endpoint, level_watch, device_watch, changes }))
    }

    /// (percent, muted) of the default output.
    pub async fn read(&self) -> anyhow::Result<(u8, bool)> {
        // SAFETY: plain getters on an open endpoint.
        let (level, muted) = unsafe { (self.endpoint.GetMasterVolumeLevelScalar()?, self.endpoint.GetMute()?) };
        Ok((percent(level), muted.as_bool()))
    }

    pub async fn set_volume(&self, percent: u8) -> anyhow::Result<()> {
        // SAFETY: no event context; the level is in 0.0..=1.0.
        unsafe { self.endpoint.SetMasterVolumeLevelScalar(f32::from(percent.min(100)) / 100.0, std::ptr::null())? };
        Ok(())
    }

    pub async fn set_muted(&self, muted: bool) -> anyhow::Result<()> {
        // SAFETY: no event context.
        unsafe { self.endpoint.SetMute(muted, std::ptr::null())? };
        Ok(())
    }

    /// Waits for the next change to the default output or its volume; a new default device is watched from then on.
    pub async fn changed(&mut self) -> anyhow::Result<()> {
        // Never None: the callbacks hold the senders until `Drop` unregisters them.
        if let Some(Change::DefaultDevice) = self.changes.recv().await {
            let endpoint = open(&self.enumerator)?;
            // SAFETY: the callback moves from the old endpoint to the new one.
            unsafe {
                drop(self.endpoint.UnregisterControlChangeNotify(&self.level_watch));
                endpoint.RegisterControlChangeNotify(&self.level_watch)?;
            }
            self.endpoint = endpoint;
        }
        Ok(())
    }
}

impl Drop for Volume {
    fn drop(&mut self) {
        // SAFETY: both were registered in `connect`.
        unsafe {
            drop(self.endpoint.UnregisterControlChangeNotify(&self.level_watch));
            drop(self.enumerator.UnregisterEndpointNotificationCallback(&self.device_watch));
        }
    }
}

/// The volume control of the default output for the console role, the one the taskbar's slider moves.
fn open(enumerator: &IMMDeviceEnumerator) -> windows::core::Result<IAudioEndpointVolume> {
    // SAFETY: plain COM calls; the device is released when `device` drops.
    unsafe {
        let device = enumerator.GetDefaultAudioEndpoint(eRender, eConsole)?;
        device.Activate(CLSCTX_ALL, None)
    }
}

#[expect(clippy::cast_possible_truncation, clippy::cast_sign_loss, reason = "clamped to 0..=100 first")]
fn percent(level: f32) -> u8 {
    (level.clamp(0.0, 1.0) * 100.0).round() as u8
}

/// The COM classes; their `#[implement]` expansion trips these lints.
#[allow(clippy::inline_always, clippy::ref_as_ptr, reason = "code generated by windows-rs")]
mod watch {
    use tokio::sync::mpsc;
    use windows::Win32::Media::Audio::Endpoints::{IAudioEndpointVolumeCallback, IAudioEndpointVolumeCallback_Impl};
    use windows::Win32::Media::Audio::{
        AUDIO_VOLUME_NOTIFICATION_DATA, DEVICE_STATE, EDataFlow, ERole, IMMNotificationClient,
        IMMNotificationClient_Impl, eConsole, eRender,
    };
    use windows::core::{PCWSTR, implement};

    use super::Change;

    /// Called on a COM thread; the receiver is the session's loop.
    #[implement(IAudioEndpointVolumeCallback)]
    pub(super) struct LevelWatch(pub(super) mpsc::UnboundedSender<Change>);

    impl IAudioEndpointVolumeCallback_Impl for LevelWatch_Impl {
        fn OnNotify(&self, _data: *mut AUDIO_VOLUME_NOTIFICATION_DATA) -> windows::core::Result<()> {
            drop(self.0.send(Change::Level));
            Ok(())
        }
    }

    #[implement(IMMNotificationClient)]
    pub(super) struct DeviceWatch(pub(super) mpsc::UnboundedSender<Change>);

    impl IMMNotificationClient_Impl for DeviceWatch_Impl {
        fn OnDefaultDeviceChanged(&self, flow: EDataFlow, role: ERole, _id: &PCWSTR) -> windows::core::Result<()> {
            if flow == eRender && role == eConsole {
                drop(self.0.send(Change::DefaultDevice));
            }
            Ok(())
        }

        fn OnDeviceStateChanged(&self, _id: &PCWSTR, _state: DEVICE_STATE) -> windows::core::Result<()> {
            Ok(())
        }

        fn OnDeviceAdded(&self, _id: &PCWSTR) -> windows::core::Result<()> {
            Ok(())
        }

        fn OnDeviceRemoved(&self, _id: &PCWSTR) -> windows::core::Result<()> {
            Ok(())
        }

        fn OnPropertyValueChanged(
            &self,
            _id: &PCWSTR,
            _key: &windows::Win32::Foundation::PROPERTYKEY,
        ) -> windows::core::Result<()> {
            Ok(())
        }
    }
}
